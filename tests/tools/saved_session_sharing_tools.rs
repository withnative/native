use super::*;

fn sharing_owner() -> Caller {
    Caller::authenticated("acct:alice")
        .with_hosting_context("host:alice", "db:test")
        .with_hosting_owner(false)
}

async fn sharing_visibility(registry: &ToolRegistry, db: &Db, record: &str) -> bool {
    let value = call_as(
        registry,
        db,
        Caller::authenticated("acct:bea")
            .with_hosting_context("host:bea", "db:test")
            .with_hosting_owner(false),
        "get_record",
        json!({"ids":[record]}),
    )
    .await
    .unwrap();
    value["records"][0]["status"] == "found"
}

/// Generated by the actual app request planner, not a parallel Rust model.
/// The owner placeholder is bound to this disposable fixture's real person.
#[tokio::test]
async fn saved_session_share_stop_replay_preserves_audience_and_transition_fences() {
    let (db, registry, alice, bea) = fixture().await;
    let plans: Value = serde_json::from_str(
        &include_str!("../fixtures/saved-session-sharing/wire-plans.json")
            .replace("50a00000-0000-4000-8000-000000000001", &alice),
    )
    .unwrap();
    let ids = &plans["ids"];
    let root = ids["rootId"].as_str().unwrap();
    let channel = ids["channelId"].as_str().unwrap();
    let folder = ids["folderId"].as_str().unwrap();
    let record = ids["recordId"].as_str().unwrap();
    for (index, args) in plans["creates"].as_array().unwrap().iter().enumerate() {
        if index < 4 {
            create_local(&registry, &db, args.clone()).await;
        } else {
            // Pending cards/events are prepared by the ordinary bound owner,
            // matching the app's authority rather than a local-admin write.
            call_as(
                &registry,
                &db,
                sharing_owner(),
                "create_record",
                args.clone(),
            )
            .await
            .unwrap();
        }
    }
    replace_explicit_policy(
        &db,
        "test:sharing",
        root,
        vec![AllowEntry::account("acct:alice", Capability::Manage)],
    )
    .await
    .unwrap();
    // These are the actual controller's portable queries, emitted alongside
    // its write plans. Keep SQL/identity contracts under real-engine CI: an
    // anonymous placeholder or a private owner_id SQL column is not admitted.
    let identity = call_as(
        &registry,
        &db,
        sharing_owner(),
        "query_sql",
        plans["authenticatedOwnerQuery"].clone(),
    )
    .await
    .unwrap();
    assert_eq!(identity["rows"].as_array().unwrap().len(), 1);
    assert_eq!(identity["rows"][0]["id"], alice);
    assert_eq!(identity["rows"][0]["account"], "acct:alice");
    let pending = call_as(
        &registry,
        &db,
        sharing_owner(),
        "query_sql",
        plans["pendingIntentScan"].clone(),
    )
    .await
    .unwrap();
    assert_eq!(pending["rows"].as_array().unwrap().len(), 4);
    for name in ["first", "stop", "again", "competitor"] {
        assert!(pending["rows"]
            .as_array()
            .unwrap()
            .iter()
            .any(|row| row["id"] == plans[name]["items"][2]["id"]));
    }
    replace_explicit_policy(
        &db,
        "test:sharing",
        channel,
        vec![AllowEntry::account("acct:bea", Capability::View)],
    )
    .await
    .unwrap();
    assert!(!sharing_visibility(&registry, &db, record).await);

    // A later item refusal rolls back the earlier folder move and its anchor.
    let mut refused = plans["first"].clone();
    refused["idempotency_key"] = json!("nss3:fixture:bad-event");
    refused["items"][2]["if_facets"]["native.share.event.state"] = json!("committed");
    assert!(
        call_as(&registry, &db, sharing_owner(), "batch_write", refused)
            .await
            .is_err()
    );
    assert_eq!(
        projected_home_and_policy_anchor(&db, folder)
            .await
            .0
            .as_deref(),
        Some(root)
    );
    assert!(!sharing_visibility(&registry, &db, record).await);

    call_as(
        &registry,
        &db,
        sharing_owner(),
        "batch_write",
        plans["first"].clone(),
    )
    .await
    .unwrap();
    assert!(sharing_visibility(&registry, &db, record).await);
    // A visible owner profile discloses the CREATE actor, but the original
    // private root remains unreadable. Viewer provenance must not invent it
    // or relax the owner's separate access-change verification.
    replace_explicit_policy(
        &db,
        "test:visible-sharing-owner",
        &alice,
        vec![
            AllowEntry::account("acct:alice", Capability::Manage),
            AllowEntry::account("acct:bea", Capability::View),
        ],
    )
    .await
    .unwrap();
    let viewer = Caller::authenticated("acct:bea")
        .with_hosting_context("host:bea", "db:test")
        .with_hosting_owner(false);
    let public_history = call_as(
        &registry,
        &db,
        viewer.clone(),
        "get_history",
        json!({"record_id":ids["cardId"],"order":"oldest_first","detail":"full","limit":1000}),
    )
    .await
    .unwrap();
    assert_eq!(public_history["events"][0]["type"], "record.created");
    assert_eq!(public_history["events"][0]["actor"], "acct:alice");
    assert!(public_history["events"][0]["payload"]
        .as_object()
        .unwrap()
        .contains_key("home_id"));
    assert!(public_history["events"][0]["payload"]["home_id"].is_null());
    // Account/email binding rows stay private to the caller. The public
    // actor directory, gated by visible history and person View, is the
    // supported creator-to-person read; never widen bindings to fix a reader.
    let private_binding = call_as(
        &registry,
        &db,
        viewer.clone(),
        "query_sql",
        json!({"sql":"SELECT identifier FROM bindings WHERE system='account' AND record_id=?1 AND identifier='acct:alice' LIMIT 2","parameters":[alice]}),
    )
    .await
    .unwrap();
    assert!(private_binding["rows"].as_array().unwrap().is_empty());
    let public_owner = call_as(
        &registry,
        &db,
        viewer,
        "query_sql",
        plans["viewerCardOwnerQuery"].clone(),
    )
    .await
    .unwrap();
    assert_eq!(public_owner["rows"].as_array().unwrap().len(), 1);
    assert_eq!(public_owner["rows"][0]["id"], alice);
    assert_eq!(public_owner["rows"][0]["account"], "acct:alice");
    let viewer_owned = create_local(
        &registry,
        &db,
        json!({
            "id":ids["viewerOwned"],"type":"Document","kind":"note","name":"Viewer contribution",
            "owner_id":bea,"home_id":folder
        }),
    )
    .await;
    let exception = create_local(
        &registry,
        &db,
        json!({
            "id":ids["exception"],"type":"Document","kind":"note","name":"Explicit audience",
            "owner_id":alice,"home_id":folder
        }),
    )
    .await;
    replace_explicit_policy(
        &db,
        "test:sharing",
        &exception,
        vec![AllowEntry::account("acct:bea", Capability::View)],
    )
    .await
    .unwrap();

    call_as(
        &registry,
        &db,
        sharing_owner(),
        "batch_write",
        plans["stop"].clone(),
    )
    .await
    .unwrap();
    assert!(!sharing_visibility(&registry, &db, record).await);
    assert!(
        sharing_visibility(&registry, &db, &viewer_owned).await,
        "owner floor survives Stop"
    );
    assert!(
        sharing_visibility(&registry, &db, &exception).await,
        "separate audience must be disclosed"
    );
    // A queued competing first Share cannot resurrect access after Stop.
    assert!(call_as(
        &registry,
        &db,
        sharing_owner(),
        "batch_write",
        plans["competitor"].clone()
    )
    .await
    .is_err());
    assert!(!sharing_visibility(&registry, &db, record).await);

    call_as(
        &registry,
        &db,
        sharing_owner(),
        "batch_write",
        plans["again"].clone(),
    )
    .await
    .unwrap();
    assert!(sharing_visibility(&registry, &db, record).await);
    // Simulate a lost Stop reply recovered after a newer same-channel Share.
    // Its keyed receipt must not execute today's stale movement again.
    call_as(
        &registry,
        &db,
        sharing_owner(),
        "batch_write",
        plans["stop"].clone(),
    )
    .await
    .unwrap();
    assert_eq!(
        projected_home_and_policy_anchor(&db, folder)
            .await
            .0
            .as_deref(),
        Some(channel)
    );
    assert!(sharing_visibility(&registry, &db, record).await);
    db.close().await;
}

//! Deterministic TypeScript input types for the browser tool client.
//!
//! Responses deliberately stay out of this generator: handlers return
//! `serde_json::Value`, so the workbench describes only the narrow result
//! shapes it consumes. Unsupported schema constructs are errors, never `any`.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use native_ce::export::LocalSnapshotSource;
use native_ce::mcp::register_membership_tool_schema;
use native_ce::mcp::{
    register_builtin_tools, register_snapshot_tool, register_surface_tools, ToolRegistry,
};
use native_ce::{Error, Result};
use serde_json::Value;

// The aggregate CI mode deliberately lives in an existing generator target:
// adding a fifth binary would make ordinary `cargo test --no-run` builds link
// another copy of the crate. The focused binaries remain available for their
// write modes and for local diagnosis.
#[allow(dead_code)]
#[cfg(not(test))]
#[path = "guide_corpus.rs"]
mod guide_corpus;
#[allow(dead_code)]
#[cfg(not(test))]
#[path = "kind_types.rs"]
mod kind_types;
#[allow(dead_code)]
#[cfg(not(test))]
#[path = "tool_inventory.rs"]
mod tool_inventory;

const GENERATED_PATH: &str = "web/generated/tools.d.ts";
const REGENERATE_COMMAND: &str = "cargo run --features dev-tools --bin tool-types";

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Mode {
    Write,
    Check,
    CheckAll,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Check {
    ToolTypes,
    KindTypes,
    ToolInventory,
    GuideCorpus,
}

const ALL_CHECKS: [Check; 4] = [
    Check::ToolTypes,
    Check::KindTypes,
    Check::ToolInventory,
    Check::GuideCorpus,
];

impl Check {
    const fn name(self) -> &'static str {
        match self {
            Self::ToolTypes => "tool-types",
            Self::KindTypes => "kind-types",
            Self::ToolInventory => "tool-inventory",
            Self::GuideCorpus => "guide-corpus",
        }
    }
}

fn main() {
    if let Err(error) = run() {
        eprintln!("tool-types: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let mode = parse_args(std::env::args().skip(1))?;
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GENERATED_PATH);
    match mode {
        Mode::Write | Mode::Check => run_at(mode, &path),
        Mode::CheckAll => run_checks(&ALL_CHECKS, execute_check),
    }
}

fn parse_args(args: impl IntoIterator<Item = String>) -> Result<Mode> {
    let args = args.into_iter().collect::<Vec<_>>();
    match args.as_slice() {
        [] => Ok(Mode::Write),
        [arg] if arg == "--check" => Ok(Mode::Check),
        [arg] if arg == "--check-all" => Ok(Mode::CheckAll),
        _ => Err(Error::engine(format!(
            "unexpected arguments: {}; expected no arguments, `--check`, or `--check-all`",
            args.iter()
                .map(|arg| format!("`{arg}`"))
                .collect::<Vec<_>>()
                .join(" ")
        ))),
    }
}

fn run_at(mode: Mode, path: &Path) -> Result<()> {
    let expected = render()?;
    match mode {
        Mode::Write => write(path, &expected),
        Mode::Check => check(path, &expected),
        Mode::CheckAll => Err(Error::engine(
            "internal error: aggregate mode requires the generated-check dispatcher",
        )),
    }
}

#[cfg(not(test))]
fn execute_check(check: Check) -> Result<()> {
    match check {
        Check::ToolTypes => {
            let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GENERATED_PATH);
            run_at(Mode::Check, &path)
        }
        Check::KindTypes => kind_types::check_generated(),
        Check::ToolInventory => tool_inventory::check_generated(),
        Check::GuideCorpus => guide_corpus::check_generated(),
    }
}

#[cfg(test)]
fn execute_check(_check: Check) -> Result<()> {
    Err(Error::engine(
        "aggregate generated checks execute through the non-test binary",
    ))
}

fn run_checks(checks: &[Check], mut execute: impl FnMut(Check) -> Result<()>) -> Result<()> {
    let mut failures = Vec::new();
    for &check in checks {
        if let Err(error) = execute(check) {
            failures.push(format!("[{}] {error}", check.name()));
        }
    }

    if failures.is_empty() {
        Ok(())
    } else {
        Err(Error::engine(format!(
            "generated checks failed:\n{}",
            failures.join("\n")
        )))
    }
}

fn render() -> Result<Vec<u8>> {
    let mut registry = ToolRegistry::new();
    register_builtin_tools(&mut registry)?;
    register_surface_tools(&mut registry)?;
    register_snapshot_tool(
        &mut registry,
        std::sync::Arc::new(LocalSnapshotSource::new()),
    )?;
    register_membership_tool_schema(&mut registry)?;

    let mut output = String::from("// Generated by `cargo run --bin tool-types`; do not edit.\n\n");
    let names = registry
        .specs()
        .map(|tool| quoted(&tool.name))
        .collect::<Vec<_>>()
        .join(" | ");
    writeln!(output, "export type ToolName = {names};\n").expect("write String");
    output.push_str("export interface ToolArguments {\n");
    for tool in registry.specs() {
        let rendered = schema_to_ts(&tool.input_schema, &format!("{} input", tool.name))?;
        writeln!(output, "  {}: {};", quoted(&tool.name), rendered).expect("write String");
    }
    output.push_str("}\n\nexport type ToolArgs<Name extends ToolName> = ToolArguments[Name];\n");

    Ok(output.into_bytes())
}

fn write(path: &Path, expected: &[u8]) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, expected)?;
    Ok(())
}

fn check(path: &Path, expected: &[u8]) -> Result<()> {
    let actual = match fs::read(path) {
        Ok(actual) => actual,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            return Err(drift_error());
        }
        Err(error) => return Err(error.into()),
    };
    if actual != expected {
        return Err(drift_error());
    }
    Ok(())
}

fn drift_error() -> Error {
    Error::engine(format!(
        "generated tool types are stale or missing: {GENERATED_PATH}\n\
         run `{REGENERATE_COMMAND}` to regenerate them, then commit {GENERATED_PATH}"
    ))
}

fn schema_to_ts(schema: &Value, context: &str) -> Result<String> {
    let object = schema
        .as_object()
        .ok_or_else(|| Error::engine(format!("unsupported non-object JSON Schema at {context}")))?;

    for unsupported in ["$ref", "if", "then", "else", "patternProperties"] {
        if object.contains_key(unsupported) {
            return Err(Error::engine(format!(
                "unsupported JSON Schema keyword `{unsupported}` at {context}"
            )));
        }
    }

    if let Some(value) = object.get("const") {
        return literal(value, context);
    }
    if let Some(values) = object.get("enum") {
        let values = values
            .as_array()
            .ok_or_else(|| Error::engine(format!("enum is not an array at {context}")))?;
        return values
            .iter()
            .map(|value| literal(value, context))
            .collect::<Result<Vec<_>>>()
            .map(|values| values.join(" | "));
    }
    for keyword in ["oneOf", "anyOf"] {
        if let Some(branches) = object.get(keyword) {
            let branches = branches
                .as_array()
                .ok_or_else(|| Error::engine(format!("{keyword} is not an array at {context}")))?;
            return branches
                .iter()
                .enumerate()
                .map(|(index, branch)| {
                    schema_to_ts(branch, &format!("{context}.{keyword}[{index}]"))
                        .map(|value| format!("({value})"))
                })
                .collect::<Result<Vec<_>>>()
                .map(|values| values.join(" | "));
        }
    }
    if let Some(branches) = object.get("allOf") {
        let branches = branches
            .as_array()
            .ok_or_else(|| Error::engine(format!("allOf is not an array at {context}")))?;
        return branches
            .iter()
            .enumerate()
            .map(|(index, branch)| {
                schema_to_ts(branch, &format!("{context}.allOf[{index}]"))
                    .map(|value| format!("({value})"))
            })
            .collect::<Result<Vec<_>>>()
            .map(|values| values.join(" & "));
    }

    match object.get("type") {
        Some(Value::Array(types)) => types
            .iter()
            .enumerate()
            .map(|(index, kind)| type_name(kind, object, &format!("{context}.type[{index}]")))
            .collect::<Result<Vec<_>>>()
            .map(|values| values.join(" | ")),
        Some(kind) => type_name(kind, object, context),
        None if object.contains_key("properties")
            || object.contains_key("required")
            || object.contains_key("additionalProperties") =>
        {
            object_type(object, context)
        }
        None if object.keys().all(|key| {
            matches!(
                key.as_str(),
                "description" | "minProperties" | "maxProperties" | "title" | "default"
            )
        }) =>
        {
            Ok("Record<string, unknown>".to_string())
        }
        None if object.is_empty() => Ok("unknown".to_string()),
        None => Err(Error::engine(format!(
            "schema has no representable type at {context}: {schema}"
        ))),
    }
}

fn type_name(
    kind: &Value,
    schema: &serde_json::Map<String, Value>,
    context: &str,
) -> Result<String> {
    match kind.as_str() {
        Some("object") => object_type(schema, context),
        Some("array") => {
            let items = schema
                .get("items")
                .ok_or_else(|| Error::engine(format!("array has no items schema at {context}")))?;
            Ok(format!(
                "Array<{}>",
                schema_to_ts(items, &format!("{context}.items"))?
            ))
        }
        Some("string") => Ok("string".to_string()),
        Some("integer" | "number") => Ok("number".to_string()),
        Some("boolean") => Ok("boolean".to_string()),
        Some("null") => Ok("null".to_string()),
        Some(other) => Err(Error::engine(format!(
            "unsupported JSON Schema type `{other}` at {context}"
        ))),
        None => Err(Error::engine(format!(
            "schema type is not a string at {context}"
        ))),
    }
}

fn object_type(schema: &serde_json::Map<String, Value>, context: &str) -> Result<String> {
    let required = schema
        .get("required")
        .map(|value| {
            value
                .as_array()
                .ok_or_else(|| Error::engine(format!("required is not an array at {context}")))?
                .iter()
                .map(|item| {
                    item.as_str().map(str::to_string).ok_or_else(|| {
                        Error::engine(format!("required entry is not a string at {context}"))
                    })
                })
                .collect::<Result<Vec<_>>>()
        })
        .transpose()?
        .unwrap_or_default();
    let mut fields = Vec::new();
    if let Some(properties) = schema.get("properties") {
        let properties = properties
            .as_object()
            .ok_or_else(|| Error::engine(format!("properties is not an object at {context}")))?;
        for (name, property) in properties {
            let optional = if required.iter().any(|item| item == name) {
                ""
            } else {
                "?"
            };
            fields.push(format!(
                "{}{}: {}",
                quoted(name),
                optional,
                schema_to_ts(property, &format!("{context}.properties.{name}"))?
            ));
        }
    }
    for name in &required {
        let already_declared = schema
            .get("properties")
            .and_then(Value::as_object)
            .is_some_and(|properties| properties.contains_key(name));
        if !already_declared {
            fields.push(format!("{}: unknown", quoted(name)));
        }
    }
    match schema.get("additionalProperties") {
        Some(Value::Bool(true)) => fields.push("[key: string]: unknown".to_string()),
        Some(Value::Object(_)) => fields.push(format!(
            "[key: string]: {}",
            schema_to_ts(
                schema.get("additionalProperties").expect("present"),
                &format!("{context}.additionalProperties")
            )?
        )),
        Some(Value::Bool(false)) | None => {}
        Some(_) => {
            return Err(Error::engine(format!(
                "invalid additionalProperties at {context}"
            )))
        }
    }
    let base = format!("{{ {} }}", fields.join("; "));
    let Some(not) = schema.get("not") else {
        return Ok(base);
    };
    let forbidden = not
        .as_object()
        .and_then(|value| value.get("required"))
        .and_then(Value::as_array)
        .ok_or_else(|| {
            Error::engine(format!(
                "only `not: {{ required: [...] }}` is supported at {context}"
            ))
        })?;
    if forbidden.is_empty() {
        return Err(Error::engine(format!(
            "empty forbidden required set at {context}"
        )));
    }
    let alternatives = forbidden
        .iter()
        .map(|name| {
            name.as_str()
                .map(|name| format!("{{ {}?: never }}", quoted(name)))
                .ok_or_else(|| Error::engine(format!("non-string forbidden property at {context}")))
        })
        .collect::<Result<Vec<_>>>()?
        .join(" | ");
    Ok(format!("{base} & ({alternatives})"))
}

fn literal(value: &Value, context: &str) -> Result<String> {
    match value {
        Value::String(value) => Ok(quoted(value)),
        Value::Number(_) | Value::Bool(_) | Value::Null => Ok(value.to_string()),
        _ => Err(Error::engine(format!(
            "unsupported non-scalar literal at {context}"
        ))),
    }
}

fn quoted(value: &str) -> String {
    serde_json::to_string(value).expect("strings always serialize")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_write_and_check_modes_and_rejects_unknown_arguments() {
        assert_eq!(parse_args(Vec::<String>::new()).unwrap(), Mode::Write);
        assert_eq!(parse_args(["--check".to_string()]).unwrap(), Mode::Check);
        assert_eq!(
            parse_args(["--check-all".to_string()]).unwrap(),
            Mode::CheckAll
        );

        let error = parse_args(["--write".to_string()]).unwrap_err().to_string();
        assert!(error.contains("unexpected arguments: `--write`"));
        assert!(error.contains("expected no arguments, `--check`, or `--check-all`"));
    }

    #[test]
    fn aggregate_mode_dispatches_every_check_after_failures() {
        let mut dispatched = Vec::new();

        let error = run_checks(&ALL_CHECKS, |check| {
            dispatched.push(check);
            match check {
                Check::ToolTypes => Err(Error::engine("tool declaration drift")),
                Check::ToolInventory => Err(Error::engine("inventory drift")),
                Check::KindTypes | Check::GuideCorpus => Ok(()),
            }
        })
        .unwrap_err()
        .to_string();

        assert_eq!(dispatched, ALL_CHECKS);
        assert!(error.contains("[tool-types] tool declaration drift"));
        assert!(error.contains("[tool-inventory] inventory drift"));
        assert!(!error.contains("[kind-types]"));
        assert!(!error.contains("[guide-corpus]"));
    }

    #[test]
    fn aggregate_mode_succeeds_only_when_every_check_succeeds() {
        let mut dispatched = Vec::new();
        run_checks(&ALL_CHECKS, |check| {
            dispatched.push(check);
            Ok(())
        })
        .unwrap();
        assert_eq!(dispatched, ALL_CHECKS);
    }

    #[test]
    fn committed_declaration_is_current() {
        let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GENERATED_PATH);
        run_at(Mode::Check, &path).unwrap();
    }

    #[test]
    fn maximal_hosted_declaration_contains_membership_administration() {
        let rendered = String::from_utf8(render().unwrap()).unwrap();
        assert!(rendered.contains("\"manage_memberships\""));
        assert!(rendered.contains("\"action\": \"list\""));
        assert!(rendered.contains("\"action\": \"set_role\""));
        assert!(rendered.contains("\"action\": \"remove\""));
    }

    #[test]
    fn stale_declaration_fails_without_mutation() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("tools.d.ts");
        let stale = b"stale declaration\n";
        fs::write(&path, stale).unwrap();

        let error = run_at(Mode::Check, &path).unwrap_err().to_string();

        assert_eq!(fs::read(&path).unwrap(), stale);
        assert_drift_diagnostic(&error);
    }

    #[test]
    fn missing_declaration_fails_without_creating_it() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("generated/tools.d.ts");

        let error = run_at(Mode::Check, &path).unwrap_err().to_string();

        assert!(!path.exists());
        assert_drift_diagnostic(&error);
    }

    #[test]
    fn write_mode_produces_the_exact_bytes_check_mode_expects() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("generated/tools.d.ts");

        run_at(Mode::Write, &path).unwrap();

        assert_eq!(fs::read(&path).unwrap(), render().unwrap());
        run_at(Mode::Check, &path).unwrap();
    }

    fn assert_drift_diagnostic(error: &str) {
        assert!(error.contains(GENERATED_PATH));
        assert!(error.contains(REGENERATE_COMMAND));
        assert!(error.contains("commit web/generated/tools.d.ts"));
    }
}

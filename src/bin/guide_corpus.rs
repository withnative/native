//! Generate the compiled guide corpus from its repo-canonical sources.
//!
//! Most guides combine handwritten `.md.in` prose with generated contract
//! enumerations. The schema and capability guides are fully generated because
//! every claim in them is relative to the current frozen DDL or tool registry.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use native_ce::export::LocalSnapshotSource;
use native_ce::mcp::{
    register_builtin_tools, register_snapshot_tool, register_surface_tools, ExposureProfile,
    GuideSource, GuideSpec, ToolRegistry, GUIDE_SPECS,
};
use native_ce::schema::{
    canonical_ddl, ddl_sha256, SpineRelationshipDirection, ENGINE_RESERVED_FACET_KEYS,
    FROZEN_DDL_SHA256, PERSISTENCE_VALUES, SPINE_FACET_KEYS, SPINE_RELATIONSHIPS,
    SPINE_RELATIONSHIP_MEANINGS, SPINE_TYPES, SPINE_TYPE_MEANINGS,
};
use native_ce::{Error, Result, CURRENT_ENGINE_SCHEMA_VERSION};

const GUIDE_DIR: &str = "src/mcp/guides";
const REGENERATE_COMMAND: &str = "cargo run --features dev-tools --bin guide-corpus";
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Mode {
    Write,
    Check,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("guide-corpus: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let mode = parse_args(std::env::args().skip(1))?;
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GUIDE_DIR);
    run_at(mode, &root)
}

#[allow(dead_code)] // Called when this source is included by tool-types --check-all.
pub(crate) fn check_generated() -> Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GUIDE_DIR);
    run_at(Mode::Check, &root)
}

fn parse_args(args: impl IntoIterator<Item = String>) -> Result<Mode> {
    let args = args.into_iter().collect::<Vec<_>>();
    match args.as_slice() {
        [] => Ok(Mode::Write),
        [arg] if arg == "--check" => Ok(Mode::Check),
        _ => Err(Error::engine(format!(
            "unexpected arguments: {}; expected no arguments or `--check`",
            args.iter()
                .map(|arg| format!("`{arg}`"))
                .collect::<Vec<_>>()
                .join(" ")
        ))),
    }
}

fn run_at(mode: Mode, root: &Path) -> Result<()> {
    for guide in GUIDE_SPECS {
        let expected = render_guide(root, guide)?;
        let output_path = root.join(format!("{}.md", guide.topic));
        match mode {
            Mode::Write => fs::write(output_path, expected)?,
            Mode::Check => {
                let actual = fs::read_to_string(&output_path).unwrap_or_default();
                if actual != expected {
                    return Err(drift_error(guide.topic));
                }
            }
        }
    }
    Ok(())
}

fn render_guide(root: &Path, guide: GuideSpec) -> Result<String> {
    match guide.source {
        GuideSource::HandwrittenTemplate => {
            let template = fs::read_to_string(root.join(format!("{}.md.in", guide.topic)))?;
            validate_semantic_coverage(guide.topic, &template)?;
            render_template(guide.topic, &template)
        }
        GuideSource::ProductModel => {
            let mut output = generated_header("`mcp::product_model` contract and principles");
            output.push_str(&native_ce::mcp::product_model::guide_markdown());
            Ok(output)
        }
        GuideSource::FrozenSqliteDdl => render_sql_schema(),
        GuideSource::CompleteToolRegistry => {
            let registry = production_registry()?;
            render_capabilities(&registry)
        }
    }
}

fn render_template(topic: &str, template: &str) -> Result<String> {
    validate_markers(topic, template)?;
    let mut output = format!(
        "<!-- Generated by `{REGENERATE_COMMAND}` from `{topic}.md.in`; do not edit. -->\n\n{template}"
    );
    output = replace_once(
        output,
        "SPINE_TYPES",
        &markdown_list(SPINE_TYPES.iter().copied()),
    )?;
    output = replace_once(
        output,
        "SPINE_RELATIONSHIPS",
        &markdown_list(SPINE_RELATIONSHIPS.iter().copied()),
    )?;
    output = replace_once(
        output,
        "SPINE_TYPE_MEANINGS",
        &record_type_meanings_markdown(),
    )?;
    output = replace_once(
        output,
        "SPINE_RELATIONSHIP_MEANINGS",
        &relationship_meanings_markdown(),
    )?;
    output = replace_once(
        output,
        "SPINE_FACET_KEYS",
        &markdown_list(SPINE_FACET_KEYS.iter().copied()),
    )?;
    output = replace_once(
        output,
        "ENGINE_RESERVED_FACET_KEYS",
        &markdown_list(ENGINE_RESERVED_FACET_KEYS.iter().copied()),
    )?;
    output = replace_once(
        output,
        "PERSISTENCE_VALUES",
        &markdown_list(PERSISTENCE_VALUES.iter().copied()),
    )?;
    output = replace_once(
        output,
        "QUERY_SQL_CONTRACT",
        &native_ce::query::sql_contract::render_guide_contract_markdown(),
    )?;
    if output.contains("<!-- GENERATED:") {
        return Err(Error::engine(format!(
            "{topic}.md.in contains an unknown generated-section marker"
        )));
    }
    if !output.ends_with('\n') {
        output.push('\n');
    }
    Ok(output)
}

fn generated_header(source: &str) -> String {
    format!("<!-- Generated by `{REGENERATE_COMMAND}` from {source}; do not edit. -->\n\n")
}

fn render_sql_schema() -> Result<String> {
    let actual = ddl_sha256();
    if actual != FROZEN_DDL_SHA256 {
        return Err(Error::engine(format!(
            "sql-schema: compiled DDL SHA-256 {actual} disagrees with frozen pin {FROZEN_DDL_SHA256}"
        )));
    }

    let mut output = generated_header("`schema::DDL_STATEMENTS` and `FROZEN_DDL_SHA256`");
    output.push_str("# Frozen SQLite schema\n\n");
    output.push_str(
        "This is native-ce's exact ordered SQLite DDL contract for a fresh database. It is not Native App's PostgreSQL schema. Projections are rebuildable; the event logs named by the DDL remain their authorities. Use `describe_schema` for a live structured view and `query_sql` only through its documented logical catalog.\n\n",
    );
    output.push_str("## Contract identity\n\n");
    writeln!(
        output,
        "- Engine schema version: `{CURRENT_ENGINE_SCHEMA_VERSION}`"
    )
    .expect("write String");
    writeln!(
        output,
        "- Ordered DDL statements: `{}`",
        native_ce::schema::DDL_STATEMENTS.len()
    )
    .expect("write String");
    writeln!(output, "- Frozen DDL SHA-256: `{FROZEN_DDL_SHA256}`").expect("write String");
    output.push_str(
        "\nThe fingerprint is SHA-256 over the canonical statement sequence joined by `\\n;\\n`. Generation fails before writing if the compiled sequence and frozen pin disagree.\n\n## Canonical DDL\n\n```sql\n",
    );
    output.push_str(&canonical_ddl());
    output.push_str(";\n```\n");
    Ok(output)
}

fn production_registry() -> Result<ToolRegistry> {
    let mut registry = ToolRegistry::new();
    register_builtin_tools(&mut registry)?;
    register_surface_tools(&mut registry)?;
    register_snapshot_tool(&mut registry, Arc::new(LocalSnapshotSource::new()))?;
    Ok(registry)
}

/// Render from registry entries rather than a tool-name match. A later
/// integration may add overlay/protected entries or refine discovery semantics
/// by changing registry projection and this prose seam; it must not grow a
/// second handwritten capability list.
fn render_capabilities(registry: &ToolRegistry) -> Result<String> {
    registry.validate_profile_budgets()?;
    let complete_projection = registry.descriptor_projection(ExposureProfile::Complete);
    let complete_descriptor_bytes = complete_projection
        .iter()
        .map(|tool| (tool.name.as_str(), tool.descriptor_bytes()))
        .collect::<std::collections::HashMap<_, _>>();
    let focused_count = registry.specs_for_profile(ExposureProfile::Focused).count();
    let complete_count = registry
        .specs_for_profile(ExposureProfile::Complete)
        .count();
    let focused_bytes = registry.descriptor_array_bytes(ExposureProfile::Focused);
    let complete_bytes = registry.descriptor_array_bytes(ExposureProfile::Complete);

    let mut output =
        generated_header("the production complete `ToolRegistry` and exhaustive exposure metadata");
    output.push_str("# MCP capabilities\n\n");
    output.push_str(
        "This guide inventories the production direct-tool registry compiled into this build. Family, focused membership, and recovery visibility are internal discovery metadata, not authorization grants or client-visible MCP recommendation fields.\n\n## Discovery contract\n\nThe normal executor surface derives its catalogue from executable operation contracts and does not read the profiles or overlays below. Its discovery surface is currently not user-configurable.\n\nOn the legacy direct-tool transport, the default `complete` profile advertises every production-registry tool. The opt-in `focused` profile advertises only the rows marked focused below and is intentionally lossy. Stored family and per-tool overlays remain an internal compatibility and emergency-rollback seam, not a supported user-facing setting. `bootstrap` and `read_guide` are recovery tools and remain shown after every legacy overlay.\n\nLegacy exposure controls affect discovery only: omission from `tools/list` can make a tool undiscoverable and can break workflows that refer to it. A hidden tool remains callable by exact name when the caller already knows it, but the filter does not grant a capability or bypass ordinary authorization and validation. Custom overlays are not dependency-solved.\n\n## Interpretation read opt-in\n\n`get_record`, record-producing `query_record`, and `render_record` accept direct-call `include_interpretation:true`. It defaults false; absent and explicit false preserve the established payload and perform no attribution/provenance work. The opt-in is live-only and caller-authorized in one snapshot. It is limited to 50 returned bearers, 100 claims, 32 evidence rows per claim, and 256 total evidence rows, distinct inspections, and inspection-output records. Request-wide overflow returns an unavailable projection with no claim/evidence identifiers or per-bearer/global cardinality; delegation, confidence, and counts never establish endorsement, truth, or consensus. Raw claims and claim-specific Why remain exclusive to `read_attributions`.\n\nThe direct query flag is not part of saved-query v0.2 and rejects non-record terminals, `as_of`, and federated query fan-out. Federated exact get may forward it within the same 50-bearer cap; unsupported sources fail explicitly. Postgres-server and Turso-local reject the opt-in until they implement the qualified projection rather than silently omitting it. `query_sql` remains attribution-blind.\n\n",
    );
    output.push_str("Exact compact UTF-8 `result.tools` descriptor arrays:\n\n");
    writeln!(
        output,
        "- `focused`: {focused_count} tools, {focused_bytes} bytes"
    )
    .expect("write String");
    writeln!(
        output,
        "- `complete`: {complete_count} tools, {complete_bytes} bytes"
    )
    .expect("write String");
    output.push_str(
        "\n## Complete production registry\n\n| Tool | Family | Focused | Always shown | Complete | Admission reason | Descriptor bytes |\n|---|---|---:|---:|---:|---|---:|\n",
    );
    for tool in registry.specs() {
        writeln!(
            output,
            "| `{}` | `{}` | {} | {} | yes | `{}` | {} |",
            tool.name,
            tool.exposure.family.as_str(),
            if tool.exposure.focused { "yes" } else { "no" },
            if tool.exposure.always_visible {
                "yes"
            } else {
                "no"
            },
            tool.exposure.admission_reason.as_str(),
            complete_descriptor_bytes[tool.name.as_str()],
        )
        .expect("write String");
    }
    Ok(output)
}

fn replace_once(mut source: String, name: &str, replacement: &str) -> Result<String> {
    let marker = format!("<!-- GENERATED:{name} -->");
    let count = source.matches(&marker).count();
    if count > 1 {
        return Err(Error::engine(format!(
            "generated marker {marker} appears {count} times"
        )));
    }
    if count == 1 {
        source = source.replacen(&marker, replacement, 1);
    }
    Ok(source)
}

fn generated_groups(topic: &str) -> &'static [(&'static str, &'static [&'static str])] {
    match topic {
        "facets-and-vocabularies" => &[
            ("SPINE_FACET_KEYS", &SPINE_FACET_KEYS),
            ("ENGINE_RESERVED_FACET_KEYS", &ENGINE_RESERVED_FACET_KEYS),
            ("PERSISTENCE_VALUES", &PERSISTENCE_VALUES),
        ],
        "query-sql" => &[("QUERY_SQL_CONTRACT", &[])],
        _ => &[],
    }
}

fn generated_markers(topic: &str) -> &'static [&'static str] {
    match topic {
        "record-types" => &["SPINE_TYPES", "SPINE_TYPE_MEANINGS"],
        "links" => &["SPINE_RELATIONSHIPS", "SPINE_RELATIONSHIP_MEANINGS"],
        "facets-and-vocabularies" => &[
            "SPINE_FACET_KEYS",
            "ENGINE_RESERVED_FACET_KEYS",
            "PERSISTENCE_VALUES",
        ],
        "query-sql" => &["QUERY_SQL_CONTRACT"],
        _ => &[],
    }
}

fn validate_markers(topic: &str, template: &str) -> Result<()> {
    const KNOWN: [&str; 8] = [
        "SPINE_TYPES",
        "SPINE_TYPE_MEANINGS",
        "SPINE_RELATIONSHIPS",
        "SPINE_RELATIONSHIP_MEANINGS",
        "SPINE_FACET_KEYS",
        "ENGINE_RESERVED_FACET_KEYS",
        "PERSISTENCE_VALUES",
        "QUERY_SQL_CONTRACT",
    ];
    let expected = generated_markers(topic);
    for name in KNOWN {
        let marker = format!("<!-- GENERATED:{name} -->");
        let count = template.matches(&marker).count();
        let wanted = usize::from(expected.contains(&name));
        if count != wanted {
            return Err(Error::engine(format!(
                "{topic}.md.in requires generated marker {marker} exactly {wanted} time(s), found {count}"
            )));
        }
    }
    Ok(())
}

fn markdown_list<'a>(values: impl IntoIterator<Item = &'a str>) -> String {
    values
        .into_iter()
        .map(|value| format!("- `{value}`"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn record_type_meanings_markdown() -> String {
    SPINE_TYPE_MEANINGS
        .iter()
        .map(|meaning| format!("### `{}`\n\n{}", meaning.name, meaning.gloss))
        .collect::<Vec<_>>()
        .join("\n\n")
}

fn relationship_meanings_markdown() -> String {
    SPINE_RELATIONSHIP_MEANINGS
        .iter()
        .map(|meaning| {
            // The links guide states the shared direction rule once above the
            // entries. Matching here makes generation fail closed if the
            // structured catalog ever gains a direction the guide cannot
            // truthfully describe without changing that prose.
            match meaning.direction {
                SpineRelationshipDirection::Directed => {}
            }
            format!("### `{}`\n\n{}", meaning.name, meaning.gloss)
        })
        .collect::<Vec<_>>()
        .join("\n\n")
}

fn validate_semantic_coverage(topic: &str, template: &str) -> Result<()> {
    for (group, values) in generated_groups(topic) {
        for value in *values {
            let heading = format!("### `{value}`");
            let lines = template.lines().collect::<Vec<_>>();
            let Some(index) = lines.iter().position(|line| *line == heading) else {
                return Err(Error::engine(format!(
                    "{topic}.md.in must explain generated {group} value `{value}` under heading {heading}"
                )));
            };
            let has_prose = lines[index + 1..]
                .iter()
                .take_while(|line| !line.starts_with('#'))
                .any(|line| {
                    let line = line.trim();
                    !line.is_empty() && !line.starts_with("<!-- GENERATED:")
                });
            if !has_prose {
                return Err(Error::engine(format!(
                    "{topic}.md.in heading {heading} must contain non-empty handwritten prose"
                )));
            }
        }
    }
    Ok(())
}

fn drift_error(topic: &str) -> Error {
    Error::engine(format!(
        "generated guide {topic}.md is stale; run `{REGENERATE_COMMAND}`"
    ))
}


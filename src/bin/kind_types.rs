//! Deterministic core-kind identities for Rust and the Workbench.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use native_ce::meta::kind::{core_kind_manifest, core_kind_manifest_digest};
use native_ce::{Error, Result};

const RUST_PATH: &str = "src/generated/kinds.rs";
const TS_PATH: &str = "web/generated/kinds.ts";
const REGENERATE: &str = "cargo run --features dev-tools --bin kind-types";

#[derive(Clone, Copy)]
enum Mode {
    Write,
    Check,
}

fn main() {
    if let Err(error) = run() {
        eprintln!("kind-types: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<()> {
    let mode = match std::env::args().skip(1).collect::<Vec<_>>().as_slice() {
        [] => Mode::Write,
        [arg] if arg == "--check" => Mode::Check,
        args => {
            return Err(Error::engine(format!(
                "unexpected arguments: {}; expected no arguments or `--check`",
                args.join(" ")
            )))
        }
    };
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let (rust, ts) = render()?;
    apply(mode, &root.join(RUST_PATH), rust.as_bytes())?;
    apply(mode, &root.join(TS_PATH), ts.as_bytes())
}

#[allow(dead_code)] // Called when this source is included by tool-types --check-all.
pub(crate) fn check_generated() -> Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let (rust, ts) = render()?;
    apply(Mode::Check, &root.join(RUST_PATH), rust.as_bytes())?;
    apply(Mode::Check, &root.join(TS_PATH), ts.as_bytes())
}

fn variant(record_type: &str, token: &str) -> String {
    format!("{record_type}-{token}")
        .split(|character: char| !character.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn render() -> Result<(String, String)> {
    let manifest = core_kind_manifest()?;
    let digest = core_kind_manifest_digest();
    let mut rust = String::from("// Generated by `cargo run --bin kind-types`; do not edit.\n\n");
    writeln!(
        rust,
        "pub const CORE_KIND_MANIFEST_SCHEMA_VERSION: u64 = {};",
        manifest.schema_version
    )
    .unwrap();
    writeln!(
        rust,
        "pub const CORE_KIND_MANIFEST_DIGEST: &str =\n    \"{digest}\";\n"
    )
    .unwrap();
    rust.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum CoreKind {\n");
    for kind in &manifest.kinds {
        writeln!(rust, "    {},", variant(&kind.record_type, &kind.token)).unwrap();
    }
    rust.push_str("}\n\nimpl CoreKind {\n    pub const fn record_type(self) -> &'static str {\n        match self {\n");
    for kind in &manifest.kinds {
        writeln!(
            rust,
            "            Self::{} => \"{}\",",
            variant(&kind.record_type, &kind.token),
            kind.record_type
        )
        .unwrap();
    }
    rust.push_str("        }\n    }\n\n    pub const fn token(self) -> &'static str {\n        match self {\n");
    for kind in &manifest.kinds {
        writeln!(
            rust,
            "            Self::{} => \"{}\",",
            variant(&kind.record_type, &kind.token),
            kind.token
        )
        .unwrap();
    }
    rust.push_str("        }\n    }\n\n    pub const fn value_id(self) -> &'static str {\n        match self {\n");
    for kind in &manifest.kinds {
        writeln!(
            rust,
            "            Self::{} => \"{}\",",
            variant(&kind.record_type, &kind.token),
            kind.value_id
        )
        .unwrap();
    }
    rust.push_str(
        "        }\n    }\n\n    pub fn matches(self, resolution: &crate::meta::kind::KindResolution) -> bool {\n        crate::meta::kind::matches_identity(resolution, self.record_type(), self.value_id())\n    }\n\n    pub fn sql_matches(self, record_alias: &str) -> String {\n        crate::meta::kind::sql_matches_identity(record_alias, self.record_type(), self.value_id())\n    }\n}\n",
    );

    let mut ts = String::from("// Generated by `cargo run --bin kind-types`; do not edit.\n\n");
    writeln!(
        ts,
        "export const CORE_KIND_MANIFEST_SCHEMA_VERSION = {} as const;",
        manifest.schema_version
    )
    .unwrap();
    writeln!(
        ts,
        "export const CORE_KIND_MANIFEST_DIGEST = \"{digest}\" as const;\n"
    )
    .unwrap();
    ts.push_str("export const CORE_KINDS = [\n");
    for kind in &manifest.kinds {
        writeln!(
            ts,
            "  {{ type: {:?}, kind: {:?}, valueId: {:?} }},",
            kind.record_type, kind.token, kind.value_id
        )
        .unwrap();
    }
    ts.push_str("] as const;\n\nexport const CORE_KIND = {\n");
    for (index, kind) in manifest.kinds.iter().enumerate() {
        writeln!(
            ts,
            "  {}: CORE_KINDS[{index}],",
            variant(&kind.record_type, &kind.token)
        )
        .unwrap();
    }
    ts.push_str("} as const;\n\nexport type CoreKind = (typeof CORE_KINDS)[number];\n\nexport interface KindResolutionLike {\n  type: string;\n  canonical_value_id?: string | null;\n  quarantined: boolean;\n}\n\nexport function matchesCoreKind(resolution: KindResolutionLike, expected: CoreKind): boolean {\n  return !resolution.quarantined && resolution.type === expected.type && resolution.canonical_value_id === expected.valueId;\n}\n");
    Ok((rust, ts))
}

fn apply(mode: Mode, path: &Path, expected: &[u8]) -> Result<()> {
    match mode {
        Mode::Write => {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(path, expected)?;
            Ok(())
        }
        Mode::Check => match fs::read(path) {
            Ok(actual) if actual == expected => Ok(()),
            _ => Err(Error::engine(format!(
                "generated core kinds are stale or missing: {}\nrun `{REGENERATE}` and commit both generated artifacts",
                path.display()
            ))),
        },
    }
}

//! RE-FROZEN (task ff7e82b / spec fbfaf25 §2, 30 Jul 2026): the write-path break.
//! `content_events` gained three NULLABLE caller-stamped annotation columns
//! (`run_key`, `parent_key`, `intent`) plus `idx_content_events_run`, and the two
//! read-log tables (`read_log_calls`, `read_log_touches`) landed alongside `blobs`
//! and `jobs` — the direct-write species `crate::conformance::rebuild` already
//! excludes. Six new statements, 35 -> 41.
//!
//! Three things about that delta are load-bearing and easy to "tidy" wrongly:
//!
//! 1. The three new `content_events` columns are CALLER-STAMPED ANNOTATIONS. The
//!    projector must not read them — `rebuild-and-diff` is only sound while the
//!    fold ignores them, and a later convenience projection of `actor` or
//!    `intent` onto `records` would make a forgeable value load-bearing for
//!    truth. `tests/records/annotations.rs` asserts the isolation directly rather than
//!    trusting rebuild-and-diff to notice.
//! 2. `read_log_touches.record_id` carries NO foreign key, deliberately. A touch
//!    is evidence that a record was consulted; deleting the record must not
//!    erase the evidence, and `ON DELETE CASCADE` would do exactly that. It also
//!    keeps the read log droppable with no referential-integrity interaction.
//!    Dangling ids are the correct cost for a log of past observations.
//! 3. `interaction` is part of `read_log_touches`' PRIMARY KEY, so one call can
//!    record a record as both `surfaced` and `opened`. Collapsing to one row per
//!    (call, record) would destroy the numerator/denominator of `opened /
//!    surfaced` — the design's central metric — inside a single call.
//!
//! The logs have INDEPENDENT `seq` counters and one shared timeline: anything
//! ordering across event or read-log tiers must order on
//! `created_at` / `started_at`, never on `seq`.
//!
//! The read log is DISPOSABLE, and that is a promise to the user rather than an
//! implementation note — it is a surveillance record of one person's thinking
//! (verbatim query text, every record consulted, every failed search, timestamped).
//! Dropping both tables must leave every behavioral tool byte-identical apart
//! from explicitly enumerated response exemptions; `describe_schema` instead
//! mirrors the physical drop. The `read-log-disposability` conformance check
//! enforces that split differentially on every build. The engine schema stays
//! 1 — the pre-user
//! gate was re-verified immediately before this batch (hosting catalog empty, no
//! `data/users/`), which is why that historical window was cheap. This was a
//! batch COMMIT POINT, not a final freeze: while the gate held, re-pinning was
//! cheap, so further schema changes were batched into that window.
//!

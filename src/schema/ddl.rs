//! authoritative log (`meta_events`), and `events` became `content_events` — with
//! two logs the unqualified name was both ambiguous and quietly hierarchical, and
//! symmetric names put the tier boundary in the DDL itself. The engine schema
//! integer stayed 1: no schema-1 database existed in the world to migrate
//! (verified — the hosting catalog was empty and `data/users/` was empty), so
//! this corrected v1 before it shipped. That historical window was the reason
//! to do the rename then rather than later.

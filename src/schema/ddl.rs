//! Native Community Edition — current SQLite DDL. The engine schema it
//! produces is pinned by the final `PRAGMA user_version` statement below.
//!
//! This file describes only the schema compiled into the current build. Earlier
//! schema numbers were development checkpoints, not supported inputs. Until a
//! support baseline is deliberately activated, non-current files must be reset
//! or recreated.
//!
//! Faithful transcription of the decided DDL (spec: Native doc 9561d43), which
//! is itself the mechanical implementation of spine decision 2e5ed3e. The
//! statement strings below were generated byte-for-byte from the TypeScript
//! oracle (`src/schema/ddl.ts` at the freeze) — the canonical serialization
//! (`canonical_ddl()`) must keep hashing to `FROZEN_DDL_SHA256`.
//!
//! FROZEN (task 33e5aab): this file is fingerprinted by
//! `schema::contract::FROZEN_DDL_SHA256` and enforced by the conformance suite —
//! editing it fails `cargo run --bin conformance` until the contract is
//! deliberately re-frozen (bump the fingerprint, re-derive successor artifacts).
//!
//! MODEL: EVENT-AUTHORITATIVE (Fork A), on FOUR logs — one per event-sourced
//! tier. `content_events` is authoritative for the content tier
//! (`records`, `links`, `facet_values`, `facet_observations`); `meta_events` is
//! authoritative for the system/meta tier (`vocabularies`, `vocabulary_values`,
//! `schema_config`); `policy_events` is authoritative for portable policy
//! (`record_policies`, `policy_entries`); `control_events` is authoritative for
//! portable member/instruction/onboarding control state. Each is folded by its own projector
//! and verified by its own rebuild-and-diff, so drift is structurally a failing
//! test on every tier (`crate::conformance`).
//!
//! The logs stay SEPARATE, and that separation is load-bearing rather than
//! tidy-minded: `projector::project()` ends in `unknown event type`, so a meta
//! event in the content log would break `replay()` — and therefore
//! historical `as_of` reads and the content rebuild — on the first row; and
//! `content_events.record_id` is NOT NULL while meta mutations are not
//! record-scoped (`meta_events` keys on `subject_id`, the meta row's id). The
//! record projector keeps ZERO schema/vocabulary dependency as a result, which is
//! what makes content replay pure by construction.
//!
//! The `*_events` convention is BOUNDED — the absences are deliberate, not gaps.
//! `blobs` is content-addressed (immutable sha-addressed bytes have no history to
//! reconstruct); `jobs` is transient operational state (an `as_of` view of a job
//! queue is meaningless); `embeddings`, `records_fts` and `records_name_idx` are
//! derived (FTS rebuilds from its triggers on `records`).
//!
//! Statements are split one-per-entry so they can be applied as an ordered
//! batch, and ordered so every FK target table exists before its referrer.
//!
//! `PRAGMA foreign_keys` is intentionally NOT here — it is connection state, set
//! per-connection in `crate::db`. `PRAGMA user_version` is database state stored
//! in the file header and survives `VACUUM INTO`, so it remains in the exported
//! batch. The current build fingerprint covers this complete ordered batch; it
//! is not a registry of historical schema support.
//!

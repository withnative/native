//! Derivation of the stored families (slices 2b.1 and 2b.2a; briefs 87a004f
//! and 2b2a-integrated): HomeAnchor and Principal.
//!
//! The value of a home is the live gate's own nearest-anchor walk,
//! [`crate::kernel::nearest_anchor`], run over maps filled by indexed
//! primary-key probes for just the homes being derived, so a batch never
//! loads the workspace's whole topology under the writer lock. The walk reads
//! exactly the keys the probes fill (boundary first, then parent, capped at
//! [`MAX_HOME_DEPTH`]), so the partial maps give the full-map answer.
//!
//! Only `kernel_roots` homes are materialized. A home that has no root row
//! (a record home without one) has no stored row: readers treat that as
//! untrusted, never as a NULL anchor (see [`super::fence`]).

// No production caller yet (slice 2b.1 is test-only; scheduling is 2b.5).
#![cfg_attr(not(test), allow(dead_code))]

use super::*;
use std::collections::{BTreeMap, BTreeSet};

/// Is this home a policy boundary?
const BOUNDARY_SQL: &str = "SELECT EXISTS(SELECT 1 FROM main.kernel_policies WHERE root_id = ?)";
/// A home's parent; no row means the home has no root row.
const PARENT_SQL: &str = "SELECT parent_id FROM main.kernel_roots WHERE root_id = ?";
// The two rebuild streams, by primary key. A continuation is a direct
// range seek (`root_id > ?`, `generation = ? AND home > ?`): an `?1 IS NULL
// OR key > ?1` form would defeat the seek and rescan every processed key
// under the writer lock.
/// Rebuild stream 1, first page: base keys from the start.
pub(super) const ROOTS_FIRST_SQL: &str =
    "SELECT root_id FROM main.kernel_roots ORDER BY root_id LIMIT ?1";
/// Rebuild stream 1, continuation: base keys after the cursor.
pub(super) const ROOTS_AFTER_SQL: &str =
    "SELECT root_id FROM main.kernel_roots WHERE root_id > ?1 ORDER BY root_id LIMIT ?2";
/// Rebuild stream 2, first page: the generation's stored keys from the start.
pub(super) const STORED_FIRST_SQL: &str =
    "SELECT home FROM main.p_home_anchor WHERE generation = ?1 ORDER BY home LIMIT ?2";
/// Rebuild stream 2, continuation: stored keys after the cursor.
pub(super) const STORED_AFTER_SQL: &str = "SELECT home FROM main.p_home_anchor WHERE generation = ?1 AND home > ?2 ORDER BY home LIMIT ?3";
const UPSERT_SQL: &str = "INSERT INTO main.p_home_anchor (generation, home, anchor) VALUES (?, ?, ?) ON CONFLICT (generation, home) DO UPDATE SET anchor = excluded.anchor";
const DELETE_SQL: &str = "DELETE FROM main.p_home_anchor WHERE generation = ? AND home = ?";
/// Is this home in HomeAnchor's base (a `kernel_roots` row)?
const ROOTED_SQL: &str = "SELECT EXISTS(SELECT 1 FROM main.kernel_roots WHERE root_id = ?)";

/// Principal: base keys, by primary key (first page and continuation).
pub(super) const PRINCIPALS_FIRST_SQL: &str =
    "SELECT principal_id FROM main.kernel_principals ORDER BY principal_id LIMIT ?1";
pub(super) const PRINCIPALS_AFTER_SQL: &str = "SELECT principal_id FROM main.kernel_principals WHERE principal_id > ?1 ORDER BY principal_id LIMIT ?2";
pub(super) const PRINCIPAL_STORED_FIRST_SQL: &str =
    "SELECT principal FROM main.p_principal WHERE generation = ?1 ORDER BY principal LIMIT ?2";
pub(super) const PRINCIPAL_STORED_AFTER_SQL: &str = "SELECT principal FROM main.p_principal WHERE generation = ?1 AND principal > ?2 ORDER BY principal LIMIT ?3";
/// One principal's binding; no row means the principal is not in the base.
const PRINCIPAL_BINDING_SQL: &str =
    "SELECT auth_binding FROM main.kernel_principals WHERE principal_id = ?";
const PRINCIPAL_UPSERT_SQL: &str = "INSERT INTO main.p_principal (generation, principal, admitted, transform) VALUES (?, ?, ?, ?) ON CONFLICT (generation, principal) DO UPDATE SET admitted = excluded.admitted, transform = excluded.transform";
const PRINCIPAL_DELETE_SQL: &str =
    "DELETE FROM main.p_principal WHERE generation = ? AND principal = ?";

// ScopeAccess: the base universe is kernel_principals × kernel_policies in
// (principal, anchor) order, generated by strict primary-key seeks; the
// stored stream is decomposed into direct primary-key ranges. No row-value
// comparison and no `IS NULL OR` cursor form.
pub(super) const ANY_ANCHOR_SQL: &str = "SELECT EXISTS(SELECT 1 FROM main.kernel_policies)";
pub(super) const FIRST_PRINCIPAL_SQL: &str =
    "SELECT principal_id FROM main.kernel_principals ORDER BY principal_id LIMIT 1";
pub(super) const NEXT_PRINCIPAL_SQL: &str = "SELECT principal_id FROM main.kernel_principals WHERE principal_id > ?1 ORDER BY principal_id LIMIT 1";
const PRINCIPAL_EXISTS_SQL: &str =
    "SELECT EXISTS(SELECT 1 FROM main.kernel_principals WHERE principal_id = ?)";
pub(super) const ANCHORS_FIRST_SQL: &str =
    "SELECT root_id FROM main.kernel_policies ORDER BY root_id LIMIT ?1";
pub(super) const ANCHORS_AFTER_SQL: &str =
    "SELECT root_id FROM main.kernel_policies WHERE root_id > ?1 ORDER BY root_id LIMIT ?2";
pub(super) const PAIRS_FIRST_SQL: &str = "SELECT principal, anchor FROM main.p_scope_access WHERE generation = ?1 ORDER BY principal, anchor LIMIT ?2";
pub(super) const PAIRS_SAME_PRINCIPAL_SQL: &str = "SELECT principal, anchor FROM main.p_scope_access WHERE generation = ?1 AND principal = ?2 AND anchor > ?3 ORDER BY anchor LIMIT ?4";
pub(super) const PAIRS_LATER_PRINCIPALS_SQL: &str = "SELECT principal, anchor FROM main.p_scope_access WHERE generation = ?1 AND principal > ?2 ORDER BY principal, anchor LIMIT ?3";
/// A principal key's stored pairs: a primary-key prefix range.
pub(super) const PAIRS_OF_PRINCIPAL_SQL: &str = "SELECT principal, anchor FROM main.p_scope_access WHERE generation = ?1 AND principal = ?2 ORDER BY anchor LIMIT ?3";
/// An anchor key's stored pairs: a `p_scope_access_by_anchor` range.
pub(super) const PAIRS_OF_ANCHOR_SQL: &str = "SELECT principal, anchor FROM main.p_scope_access WHERE generation = ?1 AND anchor = ?2 ORDER BY principal LIMIT ?3";
/// An anchor's physical entries, in primary-key order (the order the bulk
/// gate's full scan yields them).
const ENTRIES_SQL: &str = "SELECT subject_kind, subject_id, effect, capability FROM main.kernel_policy_entries WHERE root_id = ?";
const PAIR_UPSERT_SQL: &str = "INSERT INTO main.p_scope_access (generation, principal, anchor, access) VALUES (?, ?, ?, ?) ON CONFLICT (generation, principal, anchor) DO UPDATE SET access = excluded.access";
const PAIR_DELETE_SQL: &str =
    "DELETE FROM main.p_scope_access WHERE generation = ? AND principal = ? AND anchor = ?";

/// A family's two rebuild streams and its row deletion. Every continuation
/// is a direct `key > ?` range seek.
struct Streams {
    base_first: &'static str,
    base_after: &'static str,
    stored_first: &'static str,
    stored_after: &'static str,
    delete: &'static str,
}

fn streams(family: Family) -> &'static Streams {
    match family {
        Family::HomeAnchor => &Streams {
            base_first: ROOTS_FIRST_SQL,
            base_after: ROOTS_AFTER_SQL,
            stored_first: STORED_FIRST_SQL,
            stored_after: STORED_AFTER_SQL,
            delete: DELETE_SQL,
        },
        Family::Principal => &Streams {
            base_first: PRINCIPALS_FIRST_SQL,
            base_after: PRINCIPALS_AFTER_SQL,
            stored_first: PRINCIPAL_STORED_FIRST_SQL,
            stored_after: PRINCIPAL_STORED_AFTER_SQL,
            delete: PRINCIPAL_DELETE_SQL,
        },
        Family::ScopeAccess => unreachable!("ScopeAccess keys are pairs: see the pair streams"),
    }
}

/// The SQL and fixed inputs a family's values come from, for its derivation
/// fingerprint.
pub(super) fn source_sql(family: Family) -> &'static [&'static str] {
    match family {
        Family::HomeAnchor => &[
            BOUNDARY_SQL,
            PARENT_SQL,
            ROOTS_FIRST_SQL,
            ROOTS_AFTER_SQL,
            STORED_FIRST_SQL,
            STORED_AFTER_SQL,
            UPSERT_SQL,
            DELETE_SQL,
            ROOTED_SQL,
        ],
        Family::Principal => &[
            PRINCIPALS_FIRST_SQL,
            PRINCIPALS_AFTER_SQL,
            PRINCIPAL_STORED_FIRST_SQL,
            PRINCIPAL_STORED_AFTER_SQL,
            PRINCIPAL_BINDING_SQL,
            PRINCIPAL_UPSERT_SQL,
            PRINCIPAL_DELETE_SQL,
            crate::kernel::hosted_identity::HOST_ADMISSION_BINDINGS[0],
            crate::kernel::hosted_identity::HOST_ADMISSION_BINDINGS[1],
            crate::kernel::relates_to_port::HOST_TRANSFORM_BINDING,
        ],
        Family::ScopeAccess => &[
            ANY_ANCHOR_SQL,
            FIRST_PRINCIPAL_SQL,
            NEXT_PRINCIPAL_SQL,
            PRINCIPAL_EXISTS_SQL,
            ANCHORS_FIRST_SQL,
            ANCHORS_AFTER_SQL,
            BOUNDARY_SQL,
            PAIRS_FIRST_SQL,
            PAIRS_SAME_PRINCIPAL_SQL,
            PAIRS_LATER_PRINCIPALS_SQL,
            PAIRS_OF_PRINCIPAL_SQL,
            PAIRS_OF_ANCHOR_SQL,
            ENTRIES_SQL,
            PAIR_UPSERT_SQL,
            PAIR_DELETE_SQL,
            crate::kernel::hosted_identity::POLICY_EVENT,
            crate::kernel::hosted_identity::ANCHOR_POLICY_TEMPLATES_SQL,
            crate::kernel::hosted_identity::ANCHOR_POLICY_FRONTIERS_SQL,
        ],
    }
}

/// A family's key: one text column, or ScopeAccess's (principal, anchor).
/// Ordering is per component, which is SQLite's BINARY order on each column.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub(super) enum Key {
    One(String),
    Pair(String, String),
}

impl Key {
    /// The `p_state.build_after` text: the key itself, or a JSON array of
    /// two strings, so no id character can be taken for a separator.
    pub(super) fn encode(&self) -> String {
        match self {
            Key::One(key) => key.clone(),
            Key::Pair(principal, anchor) => {
                serde_json::to_string(&[principal, anchor]).expect("strings serialize")
            }
        }
    }

    /// `None` for a cursor this family could not have written.
    pub(super) fn decode(family: Family, raw: &str) -> Option<Key> {
        match family {
            Family::HomeAnchor | Family::Principal => Some(Key::One(raw.to_owned())),
            Family::ScopeAccess => serde_json::from_str::<(String, String)>(raw)
                .ok()
                .map(|(principal, anchor)| Key::Pair(principal, anchor)),
        }
    }
}

/// The evaluator's three states for one principal at one anchor.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Access {
    /// The policy is malformed for this principal (`HIDDEN_OR_MISSING`).
    Invalid,
    ValidNoView,
    View,
}

impl Access {
    pub(super) fn code(self) -> i64 {
        match self {
            Access::Invalid => 0,
            Access::ValidNoView => 1,
            Access::View => 2,
        }
    }

    pub(super) fn from_code(code: i64) -> Option<Access> {
        match code {
            0 => Some(Access::Invalid),
            1 => Some(Access::ValidNoView),
            2 => Some(Access::View),
            _ => None,
        }
    }
}

/// A derived value of one key.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) enum Value {
    /// The nearest anchor; `None` is a broken rooted walk.
    Anchor(Option<String>),
    Principal {
        admitted: bool,
        transform: bool,
    },
    Access(Access),
}

/// One anchor's policy facts in the batch's snapshot: its physical entries
/// and, under a hosted roster, the loaded member policies (which hold the
/// anchor's current template, if any).
struct AnchorPolicy {
    entries: crate::kernel::hosted_identity::PolicyRows,
    hosted: Option<std::sync::Arc<crate::kernel::hosted_identity::MemberPolicies>>,
}

/// Facts loaded at most once per batch, in that batch's own snapshot. A new
/// cache is made for every batch; nothing here outlives its transaction.
#[derive(Default)]
pub(super) struct BatchCache {
    pub(super) probes: AncestorProbes,
    admission: Option<crate::kernel::hosted_identity::Admission>,
    anchors: BTreeMap<String, AnchorPolicy>,
}

impl BatchCache {
    /// The roster, selected once per batch. Parsing it, and each membership
    /// lookup, cost O(roster size): a disclosed 2b.5 qualification item.
    async fn admission(
        &mut self,
        conn: &mut SqliteConnection,
    ) -> Result<&crate::kernel::hosted_identity::Admission> {
        if self.admission.is_none() {
            self.admission = Some(crate::kernel::hosted_identity::admission_on(conn).await?);
        }
        Ok(self.admission.as_ref().expect("loaded above"))
    }

    /// Load the policy facts of every not-yet-loaded anchor in `anchors`
    /// with one shared hosted load. Driven from the named anchors through
    /// existing indexes; the grants, subjects, template JSON and history of
    /// each anchor are not bounded here (disclosed for 2b.5).
    async fn prefetch(
        &mut self,
        conn: &mut SqliteConnection,
        anchors: impl IntoIterator<Item = String>,
    ) -> Result<()> {
        let missing: BTreeSet<String> = anchors
            .into_iter()
            .filter(|a| !self.anchors.contains_key(a))
            .collect();
        if missing.is_empty() {
            return Ok(());
        }
        let hosted = crate::kernel::hosted_identity::load_member_policies_on(conn, Some(&missing))
            .await?
            .map(std::sync::Arc::new);
        for anchor in missing {
            let entries = sqlx::query_as(ENTRIES_SQL)
                .bind(&anchor)
                .fetch_all(&mut *conn)
                .await?;
            self.anchors.insert(
                anchor,
                AnchorPolicy {
                    entries,
                    hosted: hosted.clone(),
                },
            );
        }
        Ok(())
    }
}

/// One pair in the caller's snapshot: `None` if the principal or the anchor
/// is gone (the stored pair must go). The rows are the anchor's entries,
/// **replaced** by the hosted expansion when the anchor has a current
/// template under a roster; then the live evaluator decides. Only its
/// `HIDDEN_OR_MISSING` refusal is `Invalid`; every other error propagates.
async fn derive_pair_on(
    conn: &mut SqliteConnection,
    principal: &str,
    anchor: &str,
    cache: &mut BatchCache,
) -> Result<Option<Access>> {
    let principal_exists: bool = sqlx::query_scalar(PRINCIPAL_EXISTS_SQL)
        .bind(principal)
        .fetch_one(&mut *conn)
        .await?;
    let anchor_exists: bool = sqlx::query_scalar(BOUNDARY_SQL)
        .bind(anchor)
        .fetch_one(&mut *conn)
        .await?;
    if !principal_exists || !anchor_exists {
        return Ok(None);
    }
    cache.prefetch(conn, [anchor.to_owned()]).await?;
    let policy = &cache.anchors[anchor];
    let rows = policy
        .hosted
        .as_ref()
        .and_then(|hosted| hosted.rows_for(anchor, principal))
        .unwrap_or_else(|| policy.entries.clone());
    Ok(Some(
        match crate::kernel::evaluate_kernel_policy(principal, &rows) {
            Ok(capability) if capability.allows(Capability::View) => Access::View,
            Ok(_) => Access::ValidNoView,
            Err(Error::Engine(message)) if message == HIDDEN_OR_MISSING => Access::Invalid,
            Err(error) => return Err(error),
        },
    ))
}

/// Derive one key in the caller's snapshot: `None` if it is not in the
/// family's base (its stored row, if any, must go).
pub(super) async fn derive_on(
    conn: &mut SqliteConnection,
    family: Family,
    key: &Key,
    cache: &mut BatchCache,
) -> Result<Option<Value>> {
    match (family, key) {
        (Family::HomeAnchor, Key::One(home)) => {
            let rooted: bool = sqlx::query_scalar(ROOTED_SQL)
                .bind(home)
                .fetch_one(&mut *conn)
                .await?;
            if !rooted {
                return Ok(None);
            }
            Ok(Some(Value::Anchor(
                cache.probes.anchor_of(conn, home).await?,
            )))
        }
        (Family::Principal, Key::One(principal)) => {
            let Some(binding) = sqlx::query_scalar::<_, String>(PRINCIPAL_BINDING_SQL)
                .bind(principal)
                .fetch_optional(&mut *conn)
                .await?
            else {
                return Ok(None);
            };
            let host =
                crate::kernel::hosted_identity::HOST_ADMISSION_BINDINGS.contains(&binding.as_str());
            let transform = binding == crate::kernel::relates_to_port::HOST_TRANSFORM_BINDING;
            let admission = cache.admission(conn).await?;
            Ok(Some(Value::Principal {
                admitted: crate::kernel::hosted_identity::admitted_with(admission, host, principal),
                transform,
            }))
        }
        (Family::ScopeAccess, Key::Pair(principal, anchor)) => {
            Ok(derive_pair_on(conn, principal, anchor, cache)
                .await?
                .map(Value::Access))
        }
        _ => Err(Error::engine(
            "stored visibility key does not match its family",
        )),
    }
}

async fn upsert_on(
    conn: &mut SqliteConnection,
    generation: i64,
    key: &Key,
    value: &Value,
) -> Result<()> {
    match (key, value) {
        (Key::One(home), Value::Anchor(anchor)) => sqlx::query(UPSERT_SQL)
            .bind(generation)
            .bind(home)
            .bind(anchor),
        (
            Key::One(principal),
            Value::Principal {
                admitted,
                transform,
            },
        ) => sqlx::query(PRINCIPAL_UPSERT_SQL)
            .bind(generation)
            .bind(principal)
            .bind(admitted)
            .bind(transform),
        (Key::Pair(principal, anchor), Value::Access(access)) => sqlx::query(PAIR_UPSERT_SQL)
            .bind(generation)
            .bind(principal)
            .bind(anchor)
            .bind(access.code()),
        _ => {
            return Err(Error::engine(
                "stored visibility value does not match its key",
            ))
        }
    }
    .execute(&mut *conn)
    .await?;
    Ok(())
}

async fn delete_on(
    conn: &mut SqliteConnection,
    family: Family,
    generation: i64,
    key: &Key,
) -> Result<()> {
    match key {
        Key::One(key) => sqlx::query(streams(family).delete)
            .bind(generation)
            .bind(key),
        Key::Pair(principal, anchor) => sqlx::query(PAIR_DELETE_SQL)
            .bind(generation)
            .bind(principal)
            .bind(anchor),
    }
    .execute(&mut *conn)
    .await?;
    Ok(())
}

/// The result of a targeted key in one generation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Targeted {
    /// Every stored dependent was refreshed or deleted; this many rows of
    /// the batch's allowance were spent.
    Done(i64),
    /// More dependents than the remaining allowance: nothing was written,
    /// and the caller must escalate the family before clearing the key.
    Overflow,
}

/// The targeted path for a key whose stored dependents are one index range:
/// a principal's own row (Principal), or the stored pairs of one principal
/// or one anchor (ScopeAccess). Probes at most `remaining + 1` candidates
/// and writes nothing unless all of them fit. Only rows that are stored
/// are refreshed or deleted: a pair that is missing stays missing (never a
/// fill), and readers fall back for it.
pub(super) async fn target_on(
    conn: &mut SqliteConnection,
    family: Family,
    generation: i64,
    kind: KeyKind,
    key: &str,
    remaining: i64,
    cache: &mut BatchCache,
) -> Result<Targeted> {
    let candidates: Vec<Key> = match (family, kind) {
        (Family::ScopeAccess, KeyKind::Principal | KeyKind::Anchor) => {
            let sql = if kind == KeyKind::Principal {
                PAIRS_OF_PRINCIPAL_SQL
            } else {
                PAIRS_OF_ANCHOR_SQL
            };
            sqlx::query_as::<_, (String, String)>(sql)
                .bind(generation)
                .bind(key)
                .bind(remaining.max(0) + 1)
                .fetch_all(&mut *conn)
                .await?
                .into_iter()
                .map(|(principal, anchor)| Key::Pair(principal, anchor))
                .collect()
        }
        _ => vec![Key::One(key.to_owned())],
    };
    let cost = candidates.len() as i64;
    if cost > remaining {
        return Ok(Targeted::Overflow);
    }
    let anchors = candidates.iter().filter_map(|k| match k {
        Key::Pair(_, anchor) => Some(anchor.clone()),
        Key::One(_) => None,
    });
    cache.prefetch(conn, anchors.collect::<Vec<_>>()).await?;
    for candidate in &candidates {
        match derive_on(conn, family, candidate, cache).await? {
            Some(value) => upsert_on(conn, generation, candidate, &value).await?,
            None => delete_on(conn, family, generation, candidate).await?,
        }
    }
    Ok(Targeted::Done(cost))
}

/// Memoized probes for one batch: at most two indexed lookups per distinct
/// node, and at most `MAX_HOME_DEPTH + 1` nodes per walk.
#[derive(Default)]
pub(super) struct AncestorProbes {
    parents: BTreeMap<String, Option<String>>,
    no_root: BTreeSet<String>,
    boundaries: BTreeSet<String>,
    probed: BTreeSet<String>,
}

impl AncestorProbes {
    async fn boundary(&mut self, conn: &mut SqliteConnection, node: &str) -> Result<bool> {
        if self.probed.insert(node.to_owned()) {
            let boundary: bool = sqlx::query_scalar(BOUNDARY_SQL)
                .bind(node)
                .fetch_one(&mut *conn)
                .await?;
            if boundary {
                self.boundaries.insert(node.to_owned());
            }
        }
        Ok(self.boundaries.contains(node))
    }

    async fn parent(&mut self, conn: &mut SqliteConnection, node: &str) -> Result<Option<String>> {
        if !self.parents.contains_key(node) && !self.no_root.contains(node) {
            match sqlx::query_scalar::<_, Option<String>>(PARENT_SQL)
                .bind(node)
                .fetch_optional(&mut *conn)
                .await?
            {
                Some(parent) => {
                    self.parents.insert(node.to_owned(), parent);
                }
                None => {
                    self.no_root.insert(node.to_owned());
                }
            }
        }
        Ok(self.parents.get(node).cloned().flatten())
    }

    /// Fill the maps with every key the walk from `home` reads, in the
    /// walk's own order, then run the shared walk over them.
    pub(super) async fn anchor_of(
        &mut self,
        conn: &mut SqliteConnection,
        home: &str,
    ) -> Result<Option<String>> {
        let mut node = home.to_owned();
        let mut depth = 0usize;
        while !self.boundary(conn, &node).await? {
            depth += 1;
            if depth > MAX_HOME_DEPTH {
                break;
            }
            match self.parent(conn, &node).await? {
                Some(parent) => node = parent,
                None => break,
            }
        }
        Ok(crate::kernel::nearest_anchor(home, &self.parents, &self.boundaries).map(str::to_owned))
    }
}

/// One bounded rebuild step: what it did and where the cursor is.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct RebuildStep {
    pub derived: Vec<(Key, Value)>,
    pub deleted: Vec<Key>,
    /// The new cursor, or `None` once both streams are exhausted.
    pub cursor: Option<String>,
    /// The stored cursor could not have been written by this family: the
    /// caller resets the family to unready at the start.
    pub restart: bool,
}

/// The single-column streams after `after`, by direct range seeks.
async fn single_streams_on(
    conn: &mut SqliteConnection,
    family: Family,
    generation: i64,
    after: Option<&str>,
    limit: i64,
) -> Result<(Vec<Key>, Vec<Key>)> {
    let sql = streams(family);
    let (base, stored): (Vec<String>, Vec<String>) = match after {
        None => (
            sqlx::query_scalar(sql.base_first)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?,
            sqlx::query_scalar(sql.stored_first)
                .bind(generation)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?,
        ),
        Some(after) => (
            sqlx::query_scalar(sql.base_after)
                .bind(after)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?,
            sqlx::query_scalar(sql.stored_after)
                .bind(generation)
                .bind(after)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?,
        ),
    };
    Ok((
        base.into_iter().map(Key::One).collect(),
        stored.into_iter().map(Key::One).collect(),
    ))
}

/// The first `limit` base pairs after `after`, in (principal, anchor)
/// order, by strict primary-key seeks. With at least one anchor every
/// visited principal yields a pair, so at most `limit + 1` principals are
/// sought; with none, the base is empty after one probe. Returns fewer than
/// `limit` pairs only when the base is exhausted.
pub(super) async fn base_pairs_on(
    conn: &mut SqliteConnection,
    after: Option<(&str, &str)>,
    limit: i64,
) -> Result<Vec<Key>> {
    let mut pairs = Vec::new();
    let any_anchor: bool = sqlx::query_scalar(ANY_ANCHOR_SQL)
        .fetch_one(&mut *conn)
        .await?;
    if !any_anchor {
        return Ok(pairs);
    }
    let mut previous: Option<String> = None;
    if let Some((principal, anchor)) = after {
        let exists: bool = sqlx::query_scalar(PRINCIPAL_EXISTS_SQL)
            .bind(principal)
            .fetch_one(&mut *conn)
            .await?;
        if exists {
            let anchors: Vec<String> = sqlx::query_scalar(ANCHORS_AFTER_SQL)
                .bind(anchor)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?;
            pairs.extend(
                anchors
                    .into_iter()
                    .map(|a| Key::Pair(principal.to_owned(), a)),
            );
        }
        previous = Some(principal.to_owned());
    }
    while (pairs.len() as i64) < limit {
        let next: Option<String> = match &previous {
            None => {
                sqlx::query_scalar(FIRST_PRINCIPAL_SQL)
                    .fetch_optional(&mut *conn)
                    .await?
            }
            Some(previous) => {
                sqlx::query_scalar(NEXT_PRINCIPAL_SQL)
                    .bind(previous)
                    .fetch_optional(&mut *conn)
                    .await?
            }
        };
        let Some(principal) = next else {
            break;
        };
        let anchors: Vec<String> = sqlx::query_scalar(ANCHORS_FIRST_SQL)
            .bind(limit - pairs.len() as i64)
            .fetch_all(&mut *conn)
            .await?;
        pairs.extend(anchors.into_iter().map(|a| Key::Pair(principal.clone(), a)));
        previous = Some(principal);
    }
    Ok(pairs)
}

/// The first `limit` stored pairs of `generation` after `after`, by two
/// direct primary-key ranges.
pub(super) async fn stored_pairs_on(
    conn: &mut SqliteConnection,
    generation: i64,
    after: Option<(&str, &str)>,
    limit: i64,
) -> Result<Vec<Key>> {
    let rows: Vec<(String, String)> = match after {
        None => {
            sqlx::query_as(PAIRS_FIRST_SQL)
                .bind(generation)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?
        }
        Some((principal, anchor)) => {
            let mut rows: Vec<(String, String)> = sqlx::query_as(PAIRS_SAME_PRINCIPAL_SQL)
                .bind(generation)
                .bind(principal)
                .bind(anchor)
                .bind(limit)
                .fetch_all(&mut *conn)
                .await?;
            if (rows.len() as i64) < limit {
                rows.extend(
                    sqlx::query_as::<_, (String, String)>(PAIRS_LATER_PRINCIPALS_SQL)
                        .bind(generation)
                        .bind(principal)
                        .bind(limit - rows.len() as i64)
                        .fetch_all(&mut *conn)
                        .await?,
                );
            }
            rows
        }
    };
    Ok(rows
        .into_iter()
        .map(|(principal, anchor)| Key::Pair(principal, anchor))
        .collect())
}

/// One bounded reconciliation step of `family` in `generation` after
/// `after`: the first `limit` keys of base ∪ stored, merged in key order.
/// Base keys are re-derived; stored keys without a base row are deleted. The
/// family may become ready only when this returns `cursor: None`.
///
/// Both streams are read with the same bound, so every merged key at or
/// before the last one taken is known to be in or out of each stream.
pub(super) async fn rebuild_step_on(
    conn: &mut SqliteConnection,
    family: Family,
    generation: i64,
    after: Option<&str>,
    limit: i64,
    cache: &mut BatchCache,
) -> Result<RebuildStep> {
    let limit = limit.max(1);
    let after = match after.map(|raw| Key::decode(family, raw)) {
        Some(None) => {
            return Ok(RebuildStep {
                derived: Vec::new(),
                deleted: Vec::new(),
                cursor: None,
                restart: true,
            })
        }
        Some(Some(key)) => Some(key),
        None => None,
    };
    let (base, stored) = match (family, &after) {
        (Family::ScopeAccess, after) => {
            let after = match after {
                Some(Key::Pair(p, a)) => Some((p.as_str(), a.as_str())),
                _ => None,
            };
            (
                base_pairs_on(conn, after, limit).await?,
                stored_pairs_on(conn, generation, after, limit).await?,
            )
        }
        (_, after) => {
            let after = match after {
                Some(Key::One(key)) => Some(key.as_str()),
                _ => None,
            };
            single_streams_on(conn, family, generation, after, limit).await?
        }
    };
    let exhausted = (base.len() as i64) < limit && (stored.len() as i64) < limit;
    let in_base: BTreeSet<&Key> = base.iter().collect();
    let merged: BTreeSet<&Key> = base.iter().chain(stored.iter()).collect();
    let taken: Vec<&Key> = merged.iter().copied().take(limit as usize).collect();
    let anchors: Vec<String> = taken
        .iter()
        .filter(|k| in_base.contains(*k))
        .filter_map(|k| match k {
            Key::Pair(_, anchor) => Some(anchor.clone()),
            Key::One(_) => None,
        })
        .collect();
    cache.prefetch(conn, anchors).await?;
    let mut step = RebuildStep {
        derived: Vec::new(),
        deleted: Vec::new(),
        cursor: None,
        restart: false,
    };
    for key in &taken {
        let value = if in_base.contains(key) {
            derive_on(conn, family, key, cache).await?
        } else {
            None
        };
        match value {
            Some(value) => step.derived.push(((*key).clone(), value)),
            None => step.deleted.push((*key).clone()),
        }
    }
    if !(exhausted && merged.len() == taken.len()) {
        step.cursor = taken.last().map(|key| key.encode());
    }
    Ok(step)
}

/// Apply a computed step to `generation`.
pub(super) async fn apply_step_on(
    conn: &mut SqliteConnection,
    family: Family,
    generation: i64,
    step: &RebuildStep,
) -> Result<()> {
    for (key, value) in &step.derived {
        upsert_on(conn, generation, key, value).await?;
    }
    for key in &step.deleted {
        delete_on(conn, family, generation, key).await?;
    }
    Ok(())
}

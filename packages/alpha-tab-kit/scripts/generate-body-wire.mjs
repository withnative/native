// One owning codec/frame source; exact bootstrap/ESM/whole derivative reconciliation.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source = new URL('../../../crates/artifact-html/src/body-wire.js', import.meta.url);
const target = new URL('../src/body-wire.mjs', import.meta.url);
const factory = readFileSync(source, 'utf8');
const wrapper = `
// Capture at module evaluation; this pure helper grants no authority. Trusted
// bootstrap/parent captures before author code are wired by the private adapter.
const apply = Reflect.apply;
const typed = Object.getPrototypeOf(Uint8Array.prototype);
const wire = bodyWireFactory({
  apply, create: Object.create, define: Object.defineProperty, freeze: Object.freeze,
  own: Object.getOwnPropertyDescriptor, ownKeys: Reflect.ownKeys,
  proto: Object.getPrototypeOf, objectProto: Object.prototype, isArray: Array.isArray,
  charCode: String.prototype.charCodeAt, slice: String.prototype.slice,
  fromCharCode: String.fromCharCode, safeInteger: Number.isSafeInteger,
  parse: JSON.parse, stringify: JSON.stringify,
  Encoder: TextEncoder, Decoder: TextDecoder, decode: TextDecoder.prototype.decode,
  Bytes: Uint8Array, setBytes: Uint8Array.prototype.set,
  byteLength: Object.getOwnPropertyDescriptor(typed, 'byteLength').get,
  typedName: Object.getOwnPropertyDescriptor(typed, Symbol.toStringTag).get,
});
export function createBodyWire() { return wire; }
`;
const output = '// Generated by scripts/generate-body-wire.mjs; do not edit.\n' + factory + wrapper;
if (process.argv.length > 3 || (process.argv[2] !== undefined && process.argv[2] !== '--check')) throw new Error('expected --check or no arguments');
const checking=process.argv[2]==='--check';
// Inert exact module copies only: no pending-holder/UI import or offering.
const vendor=new URL('../../../experiments/demo-shell/public/lib/vendor/',import.meta.url);
const controllerPath=new URL('../src/body-parent-controller.mjs',import.meta.url);
const controller=readFileSync(controllerPath,'utf8');
const copies=[['body-wire.mjs',output],['body-parent-controller.mjs',controller]];
const htmlPath=new URL('../../../crates/artifact-html/src/html.rs',import.meta.url);
const bridgePath=new URL('../src/fake-host/bridge-bootstrap.js',import.meta.url);
const limitsPath=new URL('../limits.json',import.meta.url);
const frame=readFileSync(new URL('../../../crates/artifact-html/src/body-frame.js',import.meta.url),'utf8');
const original=readFileSync(htmlPath,'utf8');
const begin='/* BEGIN GENERATED BODY FACTORIES */',end='/* END GENERATED BODY FACTORIES */';
const a=original.indexOf(begin),b=original.indexOf(end,a);
if(a<0||b<0||original.indexOf(begin,a+1)>=0)throw new Error('body embedding markers');
const html=original.slice(0,a)+begin+'\n'+factory+frame+end+original.slice(b+end.length);
const bootstrap=html.match(/const BOOTSTRAP: &str = r#"([\s\S]*?)"#;/)?.[1];
if(!bootstrap)throw new Error('bootstrap extraction');
const limits=JSON.parse(readFileSync(limitsPath,'utf8'));
const digest=createHash('sha256').update(bootstrap).digest('hex');
if(checking){
 if(readFileSync(target,'utf8')!==output||original!==html||readFileSync(bridgePath,'utf8')!==bootstrap||limits.bridge.bootstrap_sha256.value!==digest)throw new Error('body factory/ESM/bootstrap/hash drift');
 for(const [name,bytes] of copies)if(readFileSync(new URL(name,vendor),'utf8')!==bytes)throw new Error('body inert vendor drift');
 console.log('body factories/ESM/production bootstrap/whole derivative/hash and inert vendor copies match');
}else{
 mkdirSync(vendor,{recursive:true});for(const [name,bytes] of copies)writeFileSync(new URL(name,vendor),bytes);
 writeFileSync(target,output);writeFileSync(htmlPath,html);writeFileSync(bridgePath,bootstrap);
 // Surgical hash replacement preserves the existing metadata formatting.
 const text=readFileSync(limitsPath,'utf8');
 const old=limits.bridge.bootstrap_sha256.value;
 if(text.split(old).length!==2)throw new Error('bootstrap hash must be unique');
 writeFileSync(limitsPath,text.replace(old,digest));
}
